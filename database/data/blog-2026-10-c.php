- **[A live photo](/en/canli-sekil).** A QR code is printed on the box; the person holds a phone over the photograph and your video plays. In a gift sent from abroad this is the closest thing to your being there.
- **[A polaroid letter](/en/mektub).** If you want more than one line, write the text in the letter — it goes inside the box.

## What to settle in advance

Three things: that the address is exact, that the phone number works, and that the day suits. Someone has to be home when the courier arrives; if the gift is a surprise that gets a little harder to arrange, and then handing the box over at a metro station, or using a relative's address, is the easier route.
